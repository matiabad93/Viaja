import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from '/tmp/viaja-smoke/node_modules/playwright/index.mjs';
const target='http://127.0.0.1:4173/';
await mkdir('artifacts/tupa-demo',{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:'/usr/bin/google-chrome',args:['--no-sandbox','--disable-dev-shm-usage']});
try{
 for(const viewport of [{width:390,height:844,name:'mobile'},{width:1280,height:900,name:'desktop'}]){
  const context=await browser.newContext({viewport,locale:'es-AR'});
  const page=await context.newPage();
  const errors=[];
  const supabaseRequests=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',request=>{if(request.url().includes('.supabase.co'))supabaseRequests.push(request.url())});
  const nav=page.locator(viewport.name==='mobile'?'.tupa-bottom-nav':'.tupa-desktop-nav');
  await page.goto(target,{waitUntil:'domcontentloaded'});
  await page.getByRole('heading',{name:/¡Bienvenido a Tupã Travel!/}).waitFor({state:'visible',timeout:22000});
  assert.equal(await page.locator('.tupa-premium-header').count(),1);
  assert.equal(await page.locator('.tupa-premium-selection').count(),1);
  const logo=page.locator('.tupa-home-emblem img');
  assert.ok(await logo.evaluate(el=>el instanceof HTMLImageElement&&el.complete&&el.naturalWidth>0),'Premium emblem loads');
  assert.ok(await page.getByRole('button',{name:/Descubrir destino/}).isVisible(),'Santorini CTA is visible');
  assert.ok(await page.getByRole('button',{name:/Ver itinerario/}).isVisible(),'Colmar editorial CTA is visible');
  const saved=await page.evaluate(()=>localStorage.getItem('tupa-travel-trips-v1'));
  assert.ok(saved,'First visit seeds isolated travel storage');
  assert.deepEqual(JSON.parse(saved),[],'A first-time visitor receives an empty private trips dashboard, never seeded demo data');
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
  assert.ok(overflow<6,'Premium mobile and desktop layouts must not have horizontal overflow: '+overflow);
  await page.screenshot({path:'artifacts/tupa-demo/'+viewport.name+'-premium-home.png',fullPage:true});
  await page.getByRole('button',{name:/Ver itinerario/}).click();
  await page.getByText('Colmar, Francia').first().waitFor({state:'visible',timeout:12000});
  const trips=await page.evaluate(()=>JSON.parse(localStorage.getItem('tupa-travel-trips-v1')||'[]'));
  assert.ok(trips.some(p=>p.trip.destination==='Colmar, Francia'&&p.itinerary?.length===3),'Featured CTA opens a persistent editable Colmar trip');
  await nav.getByRole('button',{name:/Mis viajes/}).click();
  await page.getByText('Colmar, Francia').first().waitFor({state:'visible'});
  await page.screenshot({path:'artifacts/tupa-demo/'+viewport.name+'-saved.png',fullPage:true});
  await nav.getByRole('button',{name:/Mi perfil/}).click();
  await page.getByRole('heading',{name:/Tu mundo, a tu manera/}).waitFor({state:'visible'});
  assert.ok(await page.getByRole('button',{name:/Exportar mis viajes/}).isVisible(),'Data export available');
  await page.getByLabel('Cómo querés que te llamemos').fill('Viajero');
  await page.getByRole('button',{name:/Guardar preferencia/}).click();
  assert.equal(await page.evaluate(()=>localStorage.getItem('tupa-profile-name-v1')),'Viajero');
  await page.screenshot({path:'artifacts/tupa-demo/'+viewport.name+'-profile.png',fullPage:true});
  await nav.getByRole('button',{name:/Inicio/}).click();
  await page.locator('.tupa-quick-actions').getByRole('button',{name:/Planificar/}).click();
  await page.getByRole('heading',{name:/Armá tu próximo viaje/}).waitFor({state:'visible'});
  assert.equal(supabaseRequests.length,0,'No request to Viaja production Supabase');
  assert.equal(errors.length,0,'No runtime JavaScript exceptions: '+errors.join('; '));
  await context.close();
  console.log('PASS premium Tupã '+viewport.name+': logo, Santorini/Colmar, persistent journeys, profile, HMR-ready planner and isolation');
 }
}finally{await browser.close();}
